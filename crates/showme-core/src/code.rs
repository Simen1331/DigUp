//! Code for the code index: a source file, a repo's doc or a notebook, cut into stretches of whole lines (a notebook's
//! into whole cells) that the model reads one at a time, each knowing where it is, so that a result opens there. And
//! names in code (`lookup`): a query that's a name finds the place that defines it.

use std::collections::HashMap;
use std::fs;
use std::path::Path;
use std::sync::LazyLock;

use regex::Regex;

use crate::extract::ExtractError;
use crate::model::IndexOptions;
use crate::rules;

/// A stretch of a file: its text, and its first and last lines (or cells), from 1.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Piece {
    pub text: String,
    pub first: usize,
    pub last: usize,
}

#[derive(Debug, Clone)]
pub struct CodeFile {
    pub pieces: Vec<Piece>,
    /// For the model, the file's title: its path in its repo ("payments/retry.py" in the "billing" repo reads
    /// "billing/payments/retry.py"), which says more about code than its name alone.
    pub title: String,
    /// The repo (or code project) it's in, if any.
    pub repo: Option<String>,
    pub lines: usize,
    /// A notebook's cells (code and notes; outputs are never read). None for anything else.
    pub cells: Option<usize>,
}

/// The model reads 2,048 tokens of an input at most; a single line longer than this is cut here.
pub const LONGEST_PIECE: usize = 4000;

pub fn read(path: &Path, options: &IndexOptions) -> Result<CodeFile, ExtractError> {
    let data = fs::read(path).map_err(|error| ExtractError::Unreadable(error.to_string()))?;
    let path_text = path.to_string_lossy();
    let (repo, title) = place(&path_text);
    if rules::extension(path) == "ipynb" {
        let cells = notebook_cells(&data)?;
        let text = cells.join("\n");
        // As for any code: more than this was written by a program (data pasted into a cell).
        if text.len() as u64 > options.max_code_bytes {
            return Err(ExtractError::LeftOut(format!("cells over {} MB", options.max_code_bytes >> 20)));
        }
        check(&text, true)?;
        return Ok(CodeFile {
            pieces: self::cells(&cells, options.code_stretch),
            title,
            repo,
            lines: line_count(&text),
            cells: Some(cells.len()),
        });
    }
    if data.iter().take(8000).any(|byte| *byte == 0) {
        return Err(ExtractError::LeftOut("not text".into()));
    }
    let text = match String::from_utf8(data) {
        Ok(text) => text,
        Err(error) => error.into_bytes().iter().map(|byte| *byte as char).collect(), // ISO Latin 1
    };
    check(&text, rules::SOURCE_EXTENSIONS.contains(&rules::extension(path).as_str()))?;
    Ok(CodeFile { pieces: lines(&text, options.code_stretch), title, repo, lines: line_count(&text), cells: None })
}

/// Code that's no use to read: it holds a private key, or (`source`: code, not a repo's notes) a program wrote it
/// (its generator says so at the top: "DO NOT EDIT", "@generated") or it's minified.
pub fn check(text: &str, source: bool) -> Result<(), ExtractError> {
    if text.contains("PRIVATE KEY-----") {
        return Err(ExtractError::LeftOut("holds a private key".into()));
    }
    if !source {
        return Ok(());
    }
    let top: String = text.chars().take(1000).collect();
    for mark in ["DO NOT EDIT", "@generated", "Code generated by", "Autogenerated by", "Generated by the protocol"] {
        if top.contains(mark) {
            return Err(ExtractError::LeftOut(format!("made by a program (“{mark}”)")));
        }
    }
    // Minified: few lines, and long ones (a bundle can be one line of 100,000 characters).
    let (lines, characters) = (line_count(text).max(1), text.chars().count());
    if characters / lines > 300 && text.split('\n').any(|line| line.chars().count() > 3000) {
        return Err(ExtractError::LeftOut(format!("minified ({} characters a line)", characters / lines)));
    }
    Ok(())
}

pub fn line_count(text: &str) -> usize {
    let count = text.bytes().filter(|byte| *byte == b'\n').count();
    if text.ends_with('\n') || text.is_empty() { count } else { count + 1 }
}

/// The lines of `text`: "\n" and "\r\n" both end one, as they do in an editor.
fn split_lines(text: &str) -> Vec<&str> {
    text.split('\n').map(|line| line.strip_suffix('\r').unwrap_or(line)).collect()
}

fn is_blank(line: &str) -> bool {
    line.chars().all(char::is_whitespace)
}

/// Lines that close a block (shell, Ruby, Lua, Objective-C, the C preprocessor).
const CLOSERS: &[&str] = &["end", "fi", "done", "esac", "@end", "#endif", "end;", "end)"];

/// Stretches of whole lines, each at most `size` characters (a longer line is a stretch of its own). A stretch ends,
/// when it can, where the code does: before a line that starts a new block at the left margin, or after a blank
/// line, in its last 60%. One that had to stop in the middle of a block hands its last two lines on to the next, so
/// whatever spans the cut is read whole once.
pub fn lines(text: &str, size: usize) -> Vec<Piece> {
    let mut lines = split_lines(text);
    if lines.last() == Some(&"") {
        lines.pop(); // the final newline
    }
    let count = lines.len();
    let mut offsets = Vec::with_capacity(count + 1); // characters before each line (each with its newline)
    offsets.push(0);
    for line in &lines {
        offsets.push(offsets.last().unwrap() + line.chars().count() + 1);
    }
    let blank = |index: usize| is_blank(lines[index]);
    let starts_block = |index: usize| {
        let Some(first) = lines[index].chars().next() else {
            return false;
        };
        if first.is_whitespace() {
            return false;
        }
        // A closing line belongs to the block above it.
        !"})]".contains(first) && !CLOSERS.contains(&lines[index].trim_matches([' ', '\t']))
    };

    let mut pieces = Vec::new();
    let mut start = 0;
    while start < count {
        while start < count && blank(start) {
            start += 1;
        }
        if start >= count {
            break;
        }
        let mut end = start + 1; // the stretch is lines[start..end]
        while end < count && offsets[end + 1] - offsets[start] <= size {
            end += 1;
        }
        let mut natural = end >= count;
        if !natural {
            // Where the code breaks by itself, keeping at least 40% of a stretch: a new block after a blank line
            // first, then any blank line or new block.
            let floor = offsets[start] + size * 2 / 5;
            let last_break = |is_break: &dyn Fn(usize) -> bool| {
                let mut line = end;
                while line > start + 1 && offsets[line] >= floor {
                    if is_break(line) {
                        return Some(line);
                    }
                    line -= 1;
                }
                None
            };
            let cut = last_break(&|line| starts_block(line) && blank(line - 1))
                .or_else(|| last_break(&|line| blank(line - 1) || starts_block(line)));
            if let Some(cut) = cut {
                end = cut;
                natural = true;
            }
        }
        let mut last = end;
        while last > start + 1 && blank(last - 1) {
            last -= 1; // blank lines at its end don't count
        }
        let mut body = lines[start..last].join("\n");
        if body.chars().count() > LONGEST_PIECE {
            body = body.chars().take(LONGEST_PIECE).collect();
        }
        pieces.push(Piece { text: body, first: start + 1, last });
        start = if natural { end } else { (end.saturating_sub(2)).max(start + 1) };
    }
    pieces
}

/// A stretch in one line, for result lists: its first line that defines something ("def retry_with_backoff(…"), else
/// its first line of code (not a comment, an import or a closing brace).
pub fn summary(text: &str) -> String {
    let lines: Vec<&str> = split_lines(text)
        .into_iter()
        .map(|line| line.trim_matches([' ', '\t']))
        .filter(|line| !line.is_empty())
        .collect();
    let definition = lines.iter().find(|line| line.split_whitespace().take(4).any(lookup::defines_something));
    const NOT_CODE: &[&str] =
        &["//", "#", "/*", "*", "--", "\"\"\"", "import ", "from ", "#include", "using ", "package ", "}", ")", "@"];
    let code = lines.iter().find(|line| !NOT_CODE.iter().any(|prefix| line.starts_with(prefix)));
    let line = definition.or(code).or(lines.first()).copied().unwrap_or("");
    if line.chars().count() > 160 { line.chars().take(160).collect::<String>() + "…" } else { line.to_string() }
}

/// The cells of a Jupyter notebook, code and notes alike, as their text. Outputs (pictures, tables, logs) aren't read.
pub fn notebook_cells(data: &[u8]) -> Result<Vec<String>, ExtractError> {
    let notebook: serde_json::Value =
        serde_json::from_slice(data).map_err(|_| ExtractError::Unreadable("not a notebook".into()))?;
    if !notebook.is_object() {
        return Err(ExtractError::Unreadable("not a notebook".into()));
    }
    // nbformat 4 keeps its cells at the top; nbformat 3 inside worksheets, with code in "input".
    let cells = notebook
        .get("cells")
        .and_then(|cells| cells.as_array())
        .or_else(|| notebook.pointer("/worksheets/0/cells").and_then(|cells| cells.as_array()));
    Ok(cells
        .map(|cells| {
            cells
                .iter()
                .map(|cell| {
                    let source = cell.get("source").or_else(|| cell.get("input"));
                    match source {
                        Some(serde_json::Value::Array(parts)) => {
                            parts.iter().filter_map(|part| part.as_str()).collect()
                        }
                        Some(serde_json::Value::String(text)) => text.clone(),
                        _ => String::new(),
                    }
                })
                .collect()
        })
        .unwrap_or_default())
}

/// Whole cells to a stretch, up to `size` characters; a longer cell is cut into stretches of lines that all point at
/// it. Empty cells are passed over.
pub fn cells(cells: &[String], size: usize) -> Vec<Piece> {
    let mut pieces = Vec::new();
    let (mut text, mut first, mut last) = (String::new(), 0, 0);
    let flush = |text: &mut String, first: usize, last: usize, pieces: &mut Vec<Piece>| {
        if !text.is_empty() {
            pieces.push(Piece { text: std::mem::take(text), first, last });
        }
    };
    for (index, cell) in cells.iter().enumerate() {
        let body = cell.trim();
        if body.is_empty() {
            continue;
        }
        let number = index + 1;
        let length = body.chars().count();
        if length > size {
            flush(&mut text, first, last, &mut pieces);
            pieces.extend(lines(body, size).into_iter().map(|piece| Piece {
                text: piece.text,
                first: number,
                last: number,
            }));
            continue;
        }
        if !text.is_empty() && text.chars().count() + 2 + length > size {
            flush(&mut text, first, last, &mut pieces);
        }
        if text.is_empty() {
            first = number;
            text = body.to_string();
        } else {
            text.push_str("\n\n");
            text.push_str(body);
        }
        last = number;
    }
    flush(&mut text, first, last, &mut pieces);
    pieces
}

/// The repo (or code project) `path` is in, and the file's title: its path from the repo's folder, the repo's name
/// first. Outside any: its folder's name and its own.
pub fn place(path: &str) -> (Option<String>, String) {
    let home = std::env::var("HOME").unwrap_or_default();
    let mut folder = crate::folder_selection::parent(path).to_string();
    let mut repo = None;
    while folder.len() > 1 && folder != home {
        if Path::new(&folder).join(".git").exists() || rules::is_project_root(Path::new(&folder)) {
            repo = Some(folder.clone());
            break;
        }
        folder = crate::folder_selection::parent(&folder).to_string();
    }
    if let Some(repo) = repo {
        let parent = crate::folder_selection::parent(&repo);
        let skip = if parent == "/" { 1 } else { parent.len() + 1 };
        return (Some(repo.clone()), path[skip..].to_string());
    }
    let components: Vec<&str> = path.split('/').filter(|part| !part.is_empty()).collect();
    (None, components[components.len().saturating_sub(2)..].join("/"))
}

