/// Names in code: a query that's a name finds it exactly, and the place that defines it rather than every place that
/// uses it; a result opens at the line that matched.
pub mod lookup {
    use super::*;

    /// The words keyword search keeps a name from code as ("quantize_row_q8_0_ref" → quantize row q8 0 ref, as one
    /// phrase), when the query is one: snake_case, camelCase, dotted, or with digits. None for words anyone would say
    /// ("retry", "Renamer"), which are searched as words and by meaning.
    pub fn identifier(query: &str) -> Option<Vec<String>> {
        static NAME: LazyLock<Regex> = LazyLock::new(|| {
            Regex::new(r"^[A-Za-z_$][A-Za-z0-9_$]*(?:(?:\.|::|->|#)[A-Za-z_$][A-Za-z0-9_$]*)*$").unwrap()
        });
        let mut name = query.trim();
        if let Some(stripped) = name.strip_suffix("()") {
            name = stripped;
        }
        if !NAME.is_match(name) {
            return None;
        }
        let camel = name.chars().skip(1).any(char::is_uppercase) && name.chars().any(char::is_lowercase);
        if !camel && !name.chars().any(|c| "_.:#$".contains(c) || c.is_numeric()) {
            return None;
        }
        Some(
            name.to_lowercase()
                .split(|c: char| !c.is_alphanumeric())
                .filter(|word| !word.is_empty())
                .map(String::from)
                .collect(),
        )
    }

    /// The keyword search pattern for an identifier's words: one phrase, so they match only side by side.
    pub fn phrase(words: &[String]) -> String {
        format!("\"{}\"", words.join(" "))
    }

    /// Where `name` is defined in `text` (a stretch whose first line is `first`): the line, and how surely. 2 after a
    /// word that defines something (def, func, class, function, struct, #define, @implementation…) or as a C-style
    /// definition; 1 for a declaration (the same, ending in ";"). None when the stretch only uses it.
    pub fn definition(name: &str, text: &str, first: usize) -> Option<(usize, u8)> {
        let mut best: Option<(usize, u8)> = None;
        for (offset, line) in split_lines(text).into_iter().enumerate() {
            for (start, end) in occurrences(name, line) {
                let before = line[..start].trim_matches([' ', '\t']);
                let after = line[end..].trim_matches([' ', '\t']);
                let strength = definition_strength(before, after, line);
                if strength > best.map_or(0, |best| best.1) {
                    best = Some((first + offset, strength));
                }
                if strength == 2 {
                    return best;
                }
            }
        }
        best
    }

    const DEFINERS: &[&str] = &[
        "def",
        "func",
        "fn",
        "fun",
        "function",
        "class",
        "struct",
        "enum",
        "protocol",
        "interface",
        "trait",
        "type",
        "typealias",
        "actor",
        "extension",
        "impl",
        "module",
        "namespace",
        "object",
        "record",
        "macro",
        "const",
        "let",
        "var",
        "val",
        "union",
        "mod",
        "sub",
        "@interface",
        "@implementation",
        "@protocol",
        "#define",
        "function*",
    ];
    /// Words before a name that mean it's being used, not defined ("await name(…)", "return name(…)").
    const USERS: &[&str] = &[
        "return", "await", "yield", "throw", "new", "else", "case", "print", "echo", "assert", "not", "and", "or",
        "in", "is", "do", "go", "defer", "try", "catch", "if", "while", "for", "typeof", "delete", "raise", "import",
        "from",
    ];

    /// A word that starts a definition ("def", "func", "class", "@implementation"…).
    pub fn defines_something(word: &str) -> bool {
        DEFINERS.contains(&word) && !["let", "var", "const", "val"].contains(&word)
    }

    fn definition_strength(before: &str, after: &str, line: &str) -> u8 {
        let previous = before.split_whitespace().last().unwrap_or("");
        if DEFINERS.contains(&previous) {
            return 2;
        }
        if before.starts_with("func (") && before.ends_with(')') {
            return 2; // a Go method
        }
        if before.starts_with("- (") || before.starts_with("+ (") {
            // an Objective-C method
            let ends = after.starts_with(':') || after.is_empty() || after.starts_with('{') || after.starts_with(';');
            return if ends { 2 } else { 0 };
        }
        // C-style: "static void name(…) {", "struct gguf_context * name(…)", not a call or an assignment.
        let Some(last) = before.chars().last() else { return 0 };
        if !after.starts_with('(')
            || USERS.contains(&previous)
            || before.chars().any(|c| "=(,.!?".contains(c))
            || before.contains("->")
            || !(last.is_alphanumeric() || "*&>_]".contains(last))
        {
            return 0;
        }
        if line.trim_matches([' ', '\t']).ends_with(';') { 1 } else { 2 }
    }

    /// The line (from `first`) to open at for `words`: the first line with one of them that defines something, else
    /// the first such line of code (not a comment), else the first such line. A word counts as itself or as a part of
    /// a name (the "retry" of retryWithBackoff and retry_with_backoff). None when none is there.
    pub fn first_line(words: &[String], text: &str, first: usize) -> Option<usize> {
        let words: Vec<String> =
            words.iter().filter(|word| word.chars().count() >= 2).map(|word| word.to_lowercase()).collect();
        if words.is_empty() {
            return None;
        }
        const COMMENT_STARTS: &[&str] = &["//", "#", "/*", "*", "--", "\"\"\"", "'''", "<!--", ";"];
        let (mut first_code, mut first_any) = (None, None);
        for (offset, line) in split_lines(text).into_iter().enumerate() {
            if !words.iter().any(|word| has(word, line)) {
                continue;
            }
            let trimmed = line.trim_matches([' ', '\t']);
            if trimmed.split_whitespace().take(4).any(defines_something) {
                return Some(first + offset);
            }
            if first_code.is_none() && !COMMENT_STARTS.iter().any(|start| trimmed.starts_with(start)) {
                first_code = Some(offset);
            }
            if first_any.is_none() {
                first_any = Some(offset);
            }
        }
        first_code.or(first_any).map(|offset| first + offset)
    }

    /// Whether `line` has `word` (lowercased) as a word or as the start of a name's part.
    fn has(word: &str, line: &str) -> bool {
        let original: Vec<char> = line.chars().collect();
        let lower: Vec<char> = original.iter().map(|c| c.to_lowercase().next().unwrap_or(*c)).collect();
        let word: Vec<char> = word.chars().collect();
        if word.is_empty() || word.len() > lower.len() {
            return false;
        }
        (0..=lower.len() - word.len()).any(|at| {
            lower[at..at + word.len()] == word[..]
                && (at == 0 || !lower[at - 1].is_alphanumeric() || original[at].is_uppercase())
        })
    }

    /// Where `name` is in `line` as a whole name (not a part of a longer one), whatever its (ASCII) case, as bytes.
    fn occurrences(name: &str, line: &str) -> Vec<(usize, usize)> {
        let (bytes, needle) = (line.as_bytes(), name.as_bytes());
        let is_name = |byte: u8| byte.is_ascii_alphanumeric() || byte == b'_' || byte == b'$' || byte >= 0x80;
        let mut found = Vec::new();
        if needle.is_empty() || needle.len() > bytes.len() {
            return found;
        }
        let mut at = 0;
        while at + needle.len() <= bytes.len() {
            if bytes[at..at + needle.len()].eq_ignore_ascii_case(needle) {
                let end = at + needle.len();
                let clear_before = at == 0 || !is_name(bytes[at - 1]);
                let clear_after = end == bytes.len() || !is_name(bytes[end]);
                if clear_before && clear_after && line.is_char_boundary(at) && line.is_char_boundary(end) {
                    found.push((at, end));
                }
                at = end;
            } else {
                at += 1;
            }
        }
        found
    }
}

